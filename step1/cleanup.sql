DROP TABLE IF EXISTS "TMP_DATABASE_RENAMING";
CREATE TABLE "TMP_DATABASE_RENAMING" as (SELECT "NAME" as "orig", "NAME" as "renamed", 1 as "new_db_id" FROM "DBS" WHERE 1=0);
INSERT INTO "TMP_DATABASE_RENAMING" VALUES
  ('tpcds_bin_partitioned_orc_30000', 'default', 1);

-- Create helper tables
DROP TABLE IF EXISTS "TMP_TABLES_TO_DELETE";
DROP TABLE IF EXISTS "TMP_PARTITIONS_TO_DELETE";
DROP TABLE IF EXISTS "TMP_TABLE_RENAMING";
DROP TABLE IF EXISTS "TMP_PARTITION_RENAMING";

CREATE TABLE "TMP_TABLES_TO_DELETE" AS (
  SELECT "TBLS"."TBL_ID" FROM "TBLS" WHERE EXISTS (
    SELECT 1 FROM "DBS" WHERE "DBS"."DB_ID"="TBLS"."DB_ID" AND NOT EXISTS (
      SELECT 1 FROM "TMP_DATABASE_RENAMING" WHERE "DBS"."NAME" = "orig")));
CREATE TABLE "TMP_PARTITIONS_TO_DELETE" AS (
  SELECT "PART_ID" FROM "PARTITIONS" WHERE "TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE"));
CREATE TABLE "TMP_TABLE_RENAMING" AS (
  SELECT t."TBL_ID", t."TBL_NAME", d."DB_ID", d."NAME", r."renamed", r."new_db_id" as "new_db_id"
  FROM "TBLS" t, "DBS" d, "TMP_DATABASE_RENAMING" r
  WHERE t."DB_ID" = d."DB_ID" AND d."NAME" = r."orig");

CREATE TABLE "TMP_PARTITION_RENAMING" AS (
  SELECT p."PART_ID", r."TBL_ID", r."renamed"
  FROM "PARTITIONS" p, "TMP_TABLE_RENAMING" r
  WHERE p."TBL_ID" = r."TBL_ID"
  );


-- Statements to cleanup transactions related state in metastore
