SELECT * FROM "TMP_DATABASE_RENAMING";
SELECT * FROM "TMP_TABLE_RENAMING";
SELECT * FROM (SELECT * FROM "TMP_PARTITION_RENAMING" LIMIT 50) UNION ALL SELECT NULL, NULL, '(limited)';

-- Statements to replace Hive default database with tpcds

DELETE FROM "TABLE_PARAMS" WHERE "TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE");
DELETE FROM "TAB_COL_STATS" WHERE "TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE");
DELETE FROM "MV_TABLES_USED" WHERE "TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE");
DELETE FROM "TBL_PRIVS" WHERE "TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE");
DELETE FROM "PARTITION_KEYS" WHERE "TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE");
DELETE FROM "PARTITION_KEY_VALS" WHERE "PART_ID" IN (SELECT * FROM "TMP_PARTITIONS_TO_DELETE");
DELETE FROM "PARTITION_PARAMS" WHERE "PART_ID" IN (SELECT * FROM "TMP_PARTITIONS_TO_DELETE");
DELETE FROM "PART_COL_STATS" WHERE "PART_ID" IN (SELECT * FROM "TMP_PARTITIONS_TO_DELETE");
DELETE FROM "PARTITIONS" WHERE "TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE");
DELETE FROM "KEY_CONSTRAINTS" WHERE "PARENT_TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE");
DELETE FROM "KEY_CONSTRAINTS" WHERE "CHILD_TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE");

DELETE FROM "TBLS" WHERE "TBL_ID" IN (SELECT * FROM "TMP_TABLES_TO_DELETE");
DELETE FROM "PARTITIONS" WHERE "PART_ID" IN (SELECT * FROM "TMP_PARTITIONS_TO_DELETE");

UPDATE "TBLS" SET "DB_ID" = (SELECT "new_db_id" FROM "TMP_TABLE_RENAMING" r WHERE r."TBL_ID" = "TBLS"."TBL_ID")
WHERE EXISTS (SELECT 1 FROM "TMP_TABLE_RENAMING" r WHERE r."TBL_ID" = "TBLS"."TBL_ID");

UPDATE "TAB_COL_STATS" SET "DB_NAME" = (SELECT "renamed" FROM "TMP_TABLE_RENAMING" r WHERE r."TBL_ID" = "TAB_COL_STATS"."TBL_ID")
WHERE EXISTS (SELECT 1 FROM "TMP_TABLE_RENAMING" r WHERE r."TBL_ID" = "TAB_COL_STATS"."TBL_ID");

UPDATE "PART_COL_STATS" SET "DB_NAME" = (SELECT "renamed" FROM "TMP_PARTITION_RENAMING" r WHERE r."PART_ID" = "PART_COL_STATS"."PART_ID")
WHERE EXISTS (SELECT 1 FROM "TMP_PARTITION_RENAMING" r WHERE r."PART_ID" = "PART_COL_STATS"."PART_ID");

DROP TABLE IF EXISTS "TMP_DBS";
CREATE TABLE "TMP_DBS" AS (SELECT * FROM "DBS");
UPDATE "TMP_DBS" SET "DB_ID" = (SELECT "new_db_id" FROM "TMP_DATABASE_RENAMING" r WHERE "TMP_DBS"."NAME" = r."orig"),
  "NAME" = (SELECT "renamed" FROM "TMP_DATABASE_RENAMING" r WHERE "TMP_DBS"."NAME" = r."orig");
DELETE FROM "TMP_DBS" WHERE "DB_ID" IS NULL;

DELETE FROM "DBS" WHERE "DB_ID" NOT IN (SELECT "DB_ID" FROM "TMP_DBS" WHERE "DB_ID" IS NOT NULL);
UPDATE "DBS" SET ("DESC", "DB_LOCATION_URI", "NAME", "OWNER_NAME", "OWNER_TYPE",
"CTLG_NAME", "CREATE_TIME", "DB_MANAGED_LOCATION_URI", "TYPE", "DATACONNECTOR_NAME", "REMOTE_DBNAME")
= (SELECT "DESC", "DB_LOCATION_URI", "NAME", "OWNER_NAME", "OWNER_TYPE",
"CTLG_NAME", "CREATE_TIME", "DB_MANAGED_LOCATION_URI", "TYPE", "DATACONNECTOR_NAME", "REMOTE_DBNAME" FROM "TMP_DBS" tmp WHERE "DBS"."DB_ID" = tmp."DB_ID");

DELETE FROM "TABLE_PARAMS" WHERE "TBL_ID" NOT IN (SELECT "TBL_ID" FROM "TBLS");

DELETE FROM "SDS" WHERE "SD_ID" NOT IN
(
-- needs to list all tables where SD_ID is used
-- compare with $ grep -B 1 "REFERENCES .*SDS.*SD_ID" schema-dump.txt | grep "ALTER TABLE"
-- (or rg instead of grep)
  SELECT "SD_ID" FROM "BUCKETING_COLS" UNION ALL
  SELECT "SD_ID" FROM "IDXS" UNION ALL
  SELECT "SD_ID" FROM "PARTITIONS" UNION ALL
  SELECT "SD_ID" FROM "SD_PARAMS" UNION ALL
  SELECT "SD_ID" FROM "SKEWED_COL_NAMES" UNION ALL
  SELECT "SD_ID" FROM "SKEWED_COL_VALUE_LOC_MAP" UNION ALL
  SELECT "SD_ID" FROM "SORT_COLS" UNION ALL
  SELECT "SD_ID" FROM "TBLS");

-- Statements to remove potentially sensitive URIs and usernames.
UPDATE "CTLGS" SET "LOCATION_URI" = REGEXP_REPLACE("LOCATION_URI",'(s3a|hdfs)://[^/]+','hdfs://localhost:40889');
UPDATE "DBS" SET "DB_LOCATION_URI" = REGEXP_REPLACE("DB_LOCATION_URI",'(s3a|hdfs)://[^/]+','hdfs://localhost:40889');
UPDATE "DBS" SET "OWNER_NAME" = 'hive' WHERE "OWNER_NAME" IS NOT NULL AND "OWNER_NAME" <> 'public';
UPDATE "SDS" SET "LOCATION" = REGEXP_REPLACE("LOCATION",'(s3a|hdfs)://[^/]+','hdfs://localhost:40889') WHERE "LOCATION" IS NOT NULL;
UPDATE "TBLS" SET "OWNER" = 'hive' WHERE "OWNER" IS NOT NULL AND "OWNER" <> 'public';

UPDATE "TABLE_PARAMS" SET "PARAM_VALUE" = 'hive' WHERE "PARAM_KEY" = 'last_modified_by';

-- Delete temporary tables
